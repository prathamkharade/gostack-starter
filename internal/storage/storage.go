// Package storage stores blobs (media files) on local disk or any S3-compatible
// object store (Cloudflare R2, Backblaze B2, Hetzner Object Storage, MinIO, AWS S3).
// The S3 client is a ~200-line SigV4 implementation using only the standard
// library: no SDK, no dependency churn.
package storage

import (
	"context"
	"errors"
	"io"
	"regexp"
	"time"
)

var ErrNotFound = errors.New("storage: not found")

// Meta is sent with uploads so object stores/CDNs serve correct headers.
type Meta struct {
	ContentType        string
	ContentEncoding    string // "gzip" for compressed text-like files
	CacheControl       string
	ContentDisposition string
}

type Storage interface {
	Put(ctx context.Context, key string, r io.Reader, size int64, m Meta) error
	Get(ctx context.Context, key string) (io.ReadCloser, error)
	Delete(ctx context.Context, key string) error
	// URL returns a direct URL for the object, or "" when the app must stream
	// it itself (local driver). Private objects get a short-lived signed URL.
	URL(ctx context.Context, key string, public bool, ttl time.Duration) (string, error)
}

var keyRE = regexp.MustCompile(`^[a-z0-9][a-z0-9/._-]{0,255}$`)

// ValidKey guards against path traversal. Keys are generated by the app
// (e.g. "m/2026/11/<uuid>/w640.webp"), never taken from user input.
func ValidKey(k string) bool {
	if !keyRE.MatchString(k) {
		return false
	}
	for i := 0; i+1 < len(k); i++ {
		if k[i] == '.' && k[i+1] == '.' {
			return false
		}
	}
	return true
}
